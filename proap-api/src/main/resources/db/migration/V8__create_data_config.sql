-- Tabela da entidade DataConfig (período de abertura das solicitações).
-- A migration que a criava (V3__criar_tabela_data_config) foi removida do repositório,
-- então bancos novos ficavam sem a tabela. Em bancos que já a possuem (ex.: produção),
-- este script não faz nada.
CREATE TABLE IF NOT EXISTS proap.data_config (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_date TIMESTAMP,
    end_date   TIMESTAMP
);
